def _srange(g, word="range"):
    if round(g.score_low, 1) == round(g.score_high, 1):
        return ""
    return f" ({word} {g.score_low:.1f}-{g.score_high:.1f})"


def _ties(g, word, plain):
    """' (4 times, e.g. ' when several readings share the lowest DO, else plain."""
    n = g.stats[DO].ties
    return f" ({n}{word} " if n > 1 else plain


def _rng(g):
    return str(g.rank_best) if g.rank_best == g.rank_worst else f"{g.rank_best}-{g.rank_worst}"


def to_plain(md):
    """Markdown brief -> plain text for copying (no markdown symbols)."""
    lines = []
    for line in md.splitlines():
        line = re.sub(r"^#+\s*", "", line)
        line = re.sub(r"^- ", "• ", line)
        line = line.replace("**", "").replace("`", "")
        lines.append(line)
    return "\n".join(lines).strip() + "\n"


def word_count(md):
    return len(to_plain(md).replace("•", " ").split())
